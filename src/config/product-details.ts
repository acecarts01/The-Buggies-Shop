// src/config/product-details.ts - The long-form half of every product.
//
// PRODUCTS (site.ts) is imported by client components on every page, so
// everything in it ships in the shared JS chunk. The fields here - the full
// description, the assigned keywords and the tags - only render on one
// product page and in the JSON-LD, so they live in this server-only module
// and reach the client as props. Never import this file from a
// 'use client' component.
//
// FAQs are built from each product's own data (see product-faqs.ts) rather
// than stored here; an entry may still carry hand-written `faqs` to override.
//
// Keywords and tags come from the cleaned keyword bank
// (docs/keyword-research/phase0/keyword-bank-clean.csv); the per-product
// table is docs/keyword-research/phase2/product-tags.csv.

import { PRODUCTS, ProductItem } from './site';
import { buildFaqs } from './product-faqs';

export interface ProductDetails {
  fullDescription: string;
  /** The single term this page is meant to win, from the cleaned keyword bank.
   *  Absent where the bank holds no clean (non-parts) term for the product. */
  primaryKeyword?: string;
  /** Up to six secondary terms. Each keyword is assigned to exactly one page
   *  so pages never compete with each other for the same query. */
  supportingKeywords?: string[];
  /** 10 to 14 descriptive tags: brand, model, type, powertrain, spec and
   *  audience terms true of this product. Rendered on the page and in JSON-LD. */
  tags: string[];
  /** Optional hand-written FAQs. When absent they are built by buildFaqs(). */
  faqs?: { q: string; a: string }[];
}

